#!/usr/bin/env node
/**
 * cmo-ai-bridge.mjs
 *
 * Headless bridge so an AI coding agent (Claude Code, Codex CLI, ...) can drive
 * the CMO Lua loop directly from a terminal, without the React UI:
 *
 *   status          resolved CMO paths + AiAssist folder + recent log files
 *   apply           safety-gate a Lua draft and save it as a one-shot AiAssist file
 *   inbox           safety-gate a Lua draft and publish it to the polled inbox file
 *   install-poller  emit the one-time in-game poller installer (or uninstaller)
 *   logs            read-only, redacted tail of CMO ExceptionLog/LuaHistory files
 *
 * All output is a single JSON object on stdout. Every AI payload passes the
 * same unsafe-Lua gate as the UI path (os/io/require/dofile/loadfile/package/
 * debug/ScenEdit_RunScript are rejected). Only the fixed poller installer
 * template - which is bridge-owned, not AI-authored - may contain the
 * ScenEdit_RunScript loader line.
 */

import { createHash } from 'node:crypto';
import { mkdir, open, readFile, readdir, rename, rm, stat, writeFile } from 'node:fs/promises';
import path from 'node:path';
import process from 'node:process';

import {
  DEFAULT_SCRIPT_FOLDER,
  createLuaSidecar,
  sanitizeLuaSidecarFileName,
  validateLuaSidecarContent,
} from '../server/cmo-lua-sidecar-writer.mjs';
import { buildCmoLogFeedback } from '../server/cmo-log-feedback-reader.mjs';
import { describeCmoInstall, findCmoLuaRoot } from './cmo-install-locator.mjs';

export const INBOX_FILE_NAME = 'AiAssist_inbox.lua';
export const INBOX_RUNSCRIPT_PATH = `/${DEFAULT_SCRIPT_FOLDER}/${INBOX_FILE_NAME}`;
export const POLLER_EVENT_NAME = 'AiAssist Inbox Poller';
export const POLLER_TRIGGER_NAME = 'AiAssist Inbox Poller Trigger';
export const POLLER_ACTION_NAME = 'AiAssist Inbox Poller Action';

function timestampForStamp(date = new Date()) {
  const pad = (value) => String(value).padStart(2, '0');
  return [
    date.getFullYear(),
    pad(date.getMonth() + 1),
    pad(date.getDate()),
    '_',
    pad(date.getHours()),
    pad(date.getMinutes()),
    pad(date.getSeconds()),
  ].join('');
}

export function buildInboxStamp(payload, now = new Date()) {
  const digest = createHash('sha1').update(String(payload), 'utf8').digest('hex').slice(0, 8);
  return `${timestampForStamp(now)}_${digest}`;
}

export function buildInboxLua(payload, stamp) {
  const lua = validateLuaSidecarContent(payload);
  if (!/^[A-Za-z0-9_]+$/.test(stamp)) throw new Error('Invalid inbox stamp');

  return [
    '-- AiAssist inbox (generated by cmo-ai-bridge; overwritten on every publish)',
    `-- stamp: ${stamp}`,
    `local inboxStamp = '${stamp}'`,
    "if ScenEdit_GetKeyValue('aiassist_inbox_stamp') ~= inboxStamp then",
    "  ScenEdit_SetKeyValue('aiassist_inbox_stamp', inboxStamp)",
    '  local ok, err = pcall(function()',
    lua.trimEnd(),
    '  end)',
    '  if ok then',
    "    ScenEdit_SetKeyValue('aiassist_inbox_result', 'ok ' .. inboxStamp)",
    '  else',
    "    ScenEdit_SetKeyValue('aiassist_inbox_result', 'error ' .. inboxStamp .. ' ' .. tostring(err))",
    "    print('AiAssist inbox error: ' .. tostring(err))",
    '  end',
    'end',
    '',
  ].join('\n');
}

export function buildNoopInboxLua() {
  return [
    '-- AiAssist inbox (generated by cmo-ai-bridge; no payload published yet)',
    "-- Publish a payload with: node tools/cmo-ai-bridge.mjs inbox --file <draft.lua> --write",
    '',
  ].join('\n');
}

export function buildPollerInstallerLua({ interval = 0, uninstall = false } = {}) {
  const parsedInterval = Number(interval);
  if (!Number.isInteger(parsedInterval) || parsedInterval < 0 || parsedInterval > 12) {
    throw new Error('interval must be an integer between 0 and 12 (CMO RegularTime enum; 0 = every 1 second)');
  }

  const removal = [
    `local eventName = '${POLLER_EVENT_NAME}'`,
    `local triggerName = '${POLLER_TRIGGER_NAME}'`,
    `local actionName = '${POLLER_ACTION_NAME}'`,
    "pcall(function() ScenEdit_SetEventAction(eventName, {mode='remove', name=actionName}) end)",
    "pcall(function() ScenEdit_SetEventTrigger(eventName, {mode='remove', name=triggerName}) end)",
    "pcall(function() ScenEdit_SetEvent(eventName, {mode='delete'}) end)",
    "pcall(function() ScenEdit_SetTrigger({mode='delete', name=triggerName}) end)",
    "pcall(function() ScenEdit_SetAction({mode='delete', name=actionName}) end)",
  ];

  if (uninstall) {
    return [
      '-- AiAssist inbox poller UNINSTALLER (generated by cmo-ai-bridge)',
      ...removal,
      "print('AiAssist inbox poller removed.')",
      '',
    ].join('\n');
  }

  return [
    '-- AiAssist inbox poller installer (generated by cmo-ai-bridge)',
    '-- Run ONCE per scenario from the CMO Lua console. Re-running reinstalls cleanly.',
    `-- RegularTime interval enum value: ${parsedInterval} (0 = every 1 second, as used by IKE/PBEM).`,
    ...removal,
    `ScenEdit_SetTrigger({mode='add', type='RegularTime', name=triggerName, interval=${parsedInterval}})`,
    `ScenEdit_SetAction({mode='add', type='LuaScript', name=actionName, ScriptText="ScenEdit_RunScript('${INBOX_RUNSCRIPT_PATH}')"})`,
    "ScenEdit_SetEvent(eventName, {mode='add', IsRepeatable=true, IsShown=false})",
    "ScenEdit_SetEventTrigger(eventName, {mode='add', name=triggerName})",
    "ScenEdit_SetEventAction(eventName, {mode='add', name=actionName})",
    "print('AiAssist inbox poller installed. Inbox: " + INBOX_RUNSCRIPT_PATH + "')",
    '',
  ].join('\n');
}

function resolveAiAssistFolder(cmoLuaRoot) {
  const root = path.resolve(cmoLuaRoot || findCmoLuaRoot());
  return { root, folder: path.join(root, DEFAULT_SCRIPT_FOLDER) };
}

async function atomicOverwrite(targetFile, content) {
  const tmpFile = `${targetFile}.tmp`;
  await writeFile(tmpFile, content, 'utf8');
  try {
    await rename(tmpFile, targetFile);
  } catch {
    await rm(targetFile, { force: true });
    await rename(tmpFile, targetFile);
  }
}

export async function publishInbox({ payload, cmoLuaRoot, write = false, now = new Date() } = {}) {
  const stamp = buildInboxStamp(payload, now);
  const lua = buildInboxLua(payload, stamp);
  const { root, folder } = resolveAiAssistFolder(cmoLuaRoot);
  const targetFile = path.join(folder, INBOX_FILE_NAME);

  const report = {
    ok: true,
    mode: write ? 'write' : 'dry-run',
    wroteFile: false,
    cmoLuaRoot: root,
    targetFile,
    stamp,
    runScriptPath: INBOX_RUNSCRIPT_PATH,
    resultKeyValue: 'aiassist_inbox_result',
    checkResultSnippet: "print(ScenEdit_GetKeyValue('aiassist_inbox_result'))",
    note: 'With the poller installed the payload runs automatically within one trigger interval; the KeyValue guard makes repeat fires a no-op.',
  };

  if (!write) return report;

  await mkdir(folder, { recursive: true });
  await atomicOverwrite(targetFile, lua);
  return { ...report, wroteFile: true };
}

export async function writeTrustedAiAssistFile({ content, slug, cmoLuaRoot, write = false, now = new Date() } = {}) {
  const fileName = sanitizeLuaSidecarFileName({ slug, now });
  const { root, folder } = resolveAiAssistFolder(cmoLuaRoot);
  const targetFile = path.join(folder, fileName);
  const runScriptPath = `/${DEFAULT_SCRIPT_FOLDER}/${fileName}`;

  const report = {
    ok: true,
    mode: write ? 'write' : 'dry-run',
    wroteFile: false,
    cmoLuaRoot: root,
    targetFile,
    runScriptPath,
    loaderSnippet: `ScenEdit_RunScript('${runScriptPath}')`,
  };

  if (!write) return report;

  await mkdir(folder, { recursive: true });
  let handle;
  try {
    handle = await open(targetFile, 'wx');
    await handle.writeFile(content, 'utf8');
  } finally {
    await handle?.close();
  }
  return { ...report, wroteFile: true };
}

async function readPayload(options) {
  if (options.lua) return options.lua;
  if (options.file) return readFile(path.resolve(options.file), 'utf8');
  if (!process.stdin.isTTY) {
    let data = '';
    for await (const chunk of process.stdin) data += chunk;
    if (data.trim()) return data;
  }
  throw new Error('Provide Lua via --file <path>, --lua "<code>", or stdin');
}

async function commandStatus(options) {
  const install = describeCmoInstall();
  const { folder } = resolveAiAssistFolder(options.cmoLuaRoot);

  let aiAssistFiles = [];
  try {
    const entries = await readdir(folder);
    aiAssistFiles = (await Promise.all(entries
      .filter((name) => name.endsWith('.lua'))
      .map(async (name) => {
        const fileStats = await stat(path.join(folder, name));
        return { name, sizeBytes: fileStats.size, mtime: fileStats.mtime.toISOString() };
      })))
      .sort((a, b) => (a.mtime < b.mtime ? 1 : -1));
  } catch {
    aiAssistFiles = [];
  }

  const logs = await buildCmoLogFeedback({ limit: 1 });
  return {
    ok: true,
    install,
    aiAssistFolder: folder,
    aiAssistFiles: aiAssistFiles.slice(0, 20),
    inboxPublished: aiAssistFiles.some((file) => file.name === INBOX_FILE_NAME),
    pollerEventName: POLLER_EVENT_NAME,
    logsRootConfigured: logs.logsRootConfigured,
    latestLogFile: logs.files[0] ? { kind: logs.files[0].kind, fileName: logs.files[0].fileName, lastWriteTime: logs.files[0].lastWriteTime } : null,
  };
}

async function commandApply(options) {
  const payload = await readPayload(options);
  return createLuaSidecar({
    content: payload,
    slug: options.slug || 'draft',
    isPasteReady: true,
    dryRun: !options.write,
    confirmWrite: options.write === true,
    cmoLuaRoot: options.cmoLuaRoot,
  });
}

async function commandInbox(options) {
  const payload = await readPayload(options);
  return publishInbox({ payload, cmoLuaRoot: options.cmoLuaRoot, write: options.write === true });
}

async function commandInstallPoller(options) {
  const interval = options.interval === undefined ? 0 : Number(options.interval);
  const uninstall = options.uninstall === true;
  const installerLua = buildPollerInstallerLua({ interval, uninstall });

  const report = await writeTrustedAiAssistFile({
    content: installerLua,
    slug: uninstall ? 'uninstall-poller' : 'install-poller',
    cmoLuaRoot: options.cmoLuaRoot,
    write: options.write === true,
  });

  if (!uninstall && options.write === true) {
    const { folder } = resolveAiAssistFolder(options.cmoLuaRoot);
    const inboxFile = path.join(folder, INBOX_FILE_NAME);
    try {
      await stat(inboxFile);
    } catch {
      await atomicOverwrite(inboxFile, buildNoopInboxLua());
    }
  }

  return {
    ...report,
    uninstall,
    interval: uninstall ? undefined : interval,
    inboxRunScriptPath: INBOX_RUNSCRIPT_PATH,
    manualStep: `Run this once in the CMO Lua console: ${report.loaderSnippet}`,
  };
}

async function commandLogs(options) {
  return buildCmoLogFeedback({
    kind: options.kind || 'all',
    since: options.since,
    limit: options.limit ? Number(options.limit) : undefined,
    maxBytes: options.maxBytes ? Number(options.maxBytes) : undefined,
  });
}

const FLAG_KEYS = new Set(['write', 'uninstall', 'help']);
const VALUE_KEYS = new Set(['file', 'lua', 'slug', 'interval', 'kind', 'since', 'limit', 'max-bytes', 'cmo-lua-root']);

function parseArgs(argv) {
  const options = {};
  for (let index = 0; index < argv.length; index += 1) {
    const raw = argv[index];
    if (!raw.startsWith('--')) continue;
    const key = raw.slice(2);
    if (FLAG_KEYS.has(key)) {
      options[key] = true;
    } else if (VALUE_KEYS.has(key)) {
      options[key] = argv[index + 1];
      index += 1;
    } else {
      throw new Error(`Unknown option: ${raw}`);
    }
  }
  return {
    ...options,
    maxBytes: options['max-bytes'],
    cmoLuaRoot: options['cmo-lua-root'],
  };
}

function usage() {
  return [
    'Usage: node tools/cmo-ai-bridge.mjs <command> [options]',
    '',
    'Commands:',
    '  status                                     Resolved CMO paths, AiAssist files, latest log',
    '  apply  --file <lua> [--slug s] [--write]   Save a one-shot AiAssist draft (dry-run by default)',
    '  inbox  --file <lua> [--write]              Publish/overwrite the polled inbox payload',
    '  install-poller [--interval 0] [--uninstall] [--write]',
    '                                             Emit the one-time in-game poller (un)installer',
    '  logs   [--kind all|exception|lua-history] [--since ISO] [--limit N] [--max-bytes N]',
    '',
    'Lua input: --file <path>, --lua "<code>", or stdin. --cmo-lua-root overrides detection.',
  ].join('\n');
}

const COMMANDS = {
  status: commandStatus,
  apply: commandApply,
  inbox: commandInbox,
  'install-poller': commandInstallPoller,
  logs: commandLogs,
};

async function main() {
  const [command, ...rest] = process.argv.slice(2);
  if (!command || command === '--help' || command === 'help') {
    console.log(usage());
    return;
  }

  const handler = COMMANDS[command];
  if (!handler) {
    console.error(JSON.stringify({ ok: false, error: `Unknown command: ${command}` }));
    process.exitCode = 1;
    return;
  }

  try {
    const options = parseArgs(rest);
    if (options.help) {
      console.log(usage());
      return;
    }
    const result = await handler(options);
    console.log(JSON.stringify(result, null, 2));
  } catch (error) {
    console.error(JSON.stringify({ ok: false, error: error?.message || String(error) }));
    process.exitCode = 1;
  }
}

const isDirectRun = process.argv[1]
  && path.resolve(process.argv[1]).toLowerCase() === path.resolve(new URL(import.meta.url).pathname.replace(/^\/([A-Za-z]:)/, '$1')).toLowerCase();

if (isDirectRun) {
  await main();
}
