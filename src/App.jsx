function getInitialTheme() {
  if (typeof window === 'undefined') {
    return 'command';
  }

  const savedTheme = window.localStorage.getItem(THEME_STORAGE_KEY);
  return THEME_OPTIONS.some((option) => option.id === savedTheme) ? savedTheme : 'command';
}

function getInitialEditorSettings() {
  if (typeof window === 'undefined') {
    return DEFAULT_EDITOR_SETTINGS;
  }

  try {
    const savedSettings = JSON.parse(window.localStorage.getItem(EDITOR_SETTINGS_STORAGE_KEY) || '{}');
    const fontFamily = EDITOR_FONT_OPTIONS.some((option) => option.id === savedSettings.fontFamily)
      ? savedSettings.fontFamily
      : DEFAULT_EDITOR_SETTINGS.fontFamily;
    const fontSize = Number(savedSettings.fontSize);

    return {
      fontFamily,
      fontSize: Number.isFinite(fontSize) ? Math.min(Math.max(fontSize, 12), 22) : DEFAULT_EDITOR_SETTINGS.fontSize,
    };
  } catch {
    return DEFAULT_EDITOR_SETTINGS;
  }
}

function getDefaultWorkspaceState() {
  return {
    events: [createEventFromTemplate('iads_ambush')],
    activeTab: 'assistant',
    sidePaneWidth: 390,
    settings: DEFAULT_PRESET_SETTINGS,
  };
}

function getInitialWorkspaceState() {
  const fallback = getDefaultWorkspaceState();

  if (typeof window === 'undefined') {
    return fallback;
  }

  try {
    const savedState = JSON.parse(window.localStorage.getItem(WORKSPACE_STATE_STORAGE_KEY) || '{}');
    const savedSidePaneWidth = Number(savedState.sidePaneWidth);
    const legacyTabMap = {
      builder: 'guide',
      reference: 'guide',
      output: 'assistant',
    };
    const savedActiveTab = legacyTabMap[savedState.activeTab] || savedState.activeTab;
    const activeTab = WORKSPACE_TABS.some((tab) => tab.id === savedActiveTab)
      ? savedActiveTab
      : fallback.activeTab;

    return {
      events: Array.isArray(savedState.events) && savedState.events.length ? savedState.events : fallback.events,
      activeTab,
      sidePaneWidth: Number.isFinite(savedSidePaneWidth) ? Math.min(Math.max(savedSidePaneWidth, 300), 680) : fallback.sidePaneWidth,
      settings: { ...DEFAULT_PRESET_SETTINGS, ...(savedState.settings || {}) },
    };
  } catch {
    return fallback;
  }
}

function quoteFontFamily(family) {
  return family === 'ui-monospace' ? family : `"${family.replace(/"/g, '\\"')}"`;
}

function isEditorFontAvailable(option) {
  if (typeof document === 'undefined' || !document.fonts?.check) return true;
  return (option.families || [option.family]).some((family) => (
    document.fonts.check(`14px ${quoteFontFamily(family)}`)
  ));
}

function getAvailableEditorFonts() {
  const detectedFonts = EDITOR_FONT_OPTIONS.filter(isEditorFontAvailable);
  return detectedFonts.length
    ? detectedFonts
    : [EDITOR_FONT_OPTIONS.find((option) => option.id === 'consolas') || EDITOR_FONT_OPTIONS[0]];
}

