function AssistantInsertPalette({ settings, requestLuaInsert }) {
  const [customPresets] = useState(readAssistantCustomPresets);

  const insertText = (label, output) => {
    if (!window.confirm(`${label}\n\n본문에 내용을 추가하겠습니까?`)) return;
    requestLuaInsert(output, label);
  };

  const insertTemplate = (kind) => {
    const template = getTemplateDefinition(kind);
    const event = createEventFromTemplate(kind);
    const output = generatePresetLua([event], {
      ...settings,
      title: `${template.title} preset`,
      description: template.summary || settings.description,
    });
    insertText(template.title, output);
  };

  const insertPreset = (preset) => {
    const output = generatePresetLua(preset.events, { ...settings, ...(preset.settings || {}) });
    insertText(preset.name || 'Custom preset', output);
  };

  return (
    <section className="assistant-insert-palette">
      <div className="mini-title">
        <BookOpen size={16} />
        템플릿 / 프리셋 삽입
      </div>
      <p className="palette-intro">
        그룹을 펼쳐 버튼을 누르면 Lua 분석 편집기 본문에 템플릿 Lua가 추가됩니다. 기존 내용은 유지되고, 작성된 내용 아래에 이어 붙습니다.
      </p>
      <div className="assistant-insert-groups">
        {FEATURE_FORM_GROUPS.map((group) => (
          <details key={group.name} className="assistant-insert-group">
            <summary>
              <span>{group.name}</span>
              <small>{group.forms.length}</small>
            </summary>
            <p>{group.description}</p>
            <div className="assistant-insert-buttons">
              {group.forms.map((kind) => {
                const template = getTemplateDefinition(kind);
                return (
                  <button key={kind} type="button" onClick={() => insertTemplate(kind)}>
                    + {template.title}
                  </button>
                );
              })}
            </div>
          </details>
        ))}
      </div>

      <div className="assistant-custom-presets">
        <strong>사용자 지정 프리셋</strong>
        <p>Preset Guide에서 저장한 사용자 지정 프리셋을 여기에서 Lua 본문으로 호출합니다.</p>
        {customPresets.length ? (
          <div className="assistant-insert-buttons">
            {customPresets.map((preset) => (
              <button key={preset.id || preset.name} type="button" onClick={() => insertPreset(preset)}>
                + {preset.name || 'Custom preset'}
              </button>
            ))}
          </div>
        ) : (
          <p>저장한 사용자 프리셋이 아직 없습니다.</p>
        )}
      </div>
    </section>
  );
}

