function readAssistantCustomPresets() {
  if (typeof window === 'undefined') return [];

  try {
    const parsed = JSON.parse(window.localStorage.getItem(CUSTOM_PRESET_STORAGE_KEY) || '[]');
    return Array.isArray(parsed) ? parsed.filter((preset) => Array.isArray(preset?.events) && preset.events.length) : [];
  } catch {
    return [];
  }
}

